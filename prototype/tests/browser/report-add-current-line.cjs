const port=process.env.CDP_PORT||'9339';
const url=process.env.APP_URL||'http://127.0.0.1:5174/';
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));

(async()=>{
  const tab=await (await fetch(`http://127.0.0.1:${port}/json/new?${encodeURIComponent(url)}`,{method:'PUT'})).json();
  const ws=new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject});
  let id=0;const pending=new Map();
  ws.onmessage=event=>{const message=JSON.parse(event.data),entry=pending.get(message.id);if(!entry)return;pending.delete(message.id);message.error?entry[1](Error(message.error.message)):entry[0](message.result)};
  const call=(method,params={})=>new Promise((resolve,reject)=>{const current=++id;pending.set(current,[resolve,reject]);ws.send(JSON.stringify({id:current,method,params}))});
  const evaluate=async expression=>{const result=await call('Runtime.evaluate',{expression,returnByValue:true});if(result.exceptionDetails)throw Error(result.exceptionDetails.exception?.description||result.exceptionDetails.text);return result.result.value};
  const check=(condition,message)=>{if(!condition)throw Error(message)};
  const mouse=async(type,x,y,extra={})=>call('Input.dispatchMouseEvent',{type,x,y,...extra});
  const key=async(key,code=key,windowsVirtualKeyCode=0)=>{await call('Input.dispatchKeyEvent',{type:'keyDown',key,code,windowsVirtualKeyCode});await call('Input.dispatchKeyEvent',{type:'keyUp',key,code,windowsVirtualKeyCode})};
  const rect=async expression=>evaluate(`(()=>{const e=${expression};if(!e)throw Error('missing element');const r=e.getBoundingClientRect();return {x:r.left+r.width/2,y:r.top+r.height/2,top:r.top,bottom:r.bottom}})()`);
  const click=async r=>{await mouse('mouseMoved',r.x,r.y);await mouse('mousePressed',r.x,r.y,{button:'left',clickCount:1});await mouse('mouseReleased',r.x,r.y,{button:'left',clickCount:1})};
  try{
    await call('Emulation.setDeviceMetricsOverride',{width:1800,height:1200,deviceScaleFactor:1,mobile:false});
    for(let i=0;i<100&&!await evaluate("!!document.querySelector('.body-editor .tiptap > p')");i++)await wait(100);
    await evaluate("document.querySelector('.body-editor .tiptap > p').scrollIntoView({block:'center'})");
    const line="document.querySelector('.body-editor .tiptap > p')";
    await click(await rect(line));
    await call('Input.insertText',{text:'原有正文'});
    const before=await evaluate("(()=>{const e=document.querySelector('.body-editor .tiptap');return {text:e.textContent,count:e.childElementCount}})()");
    const target=await rect(line);await mouse('mouseMoved',target.x,target.y);await wait(350);
    const menu="[...document.querySelectorAll('.side-menu')].find(e=>getComputedStyle(e).visibility==='visible' && e.closest('[data-tippy-root]')?.style.visibility==='visible')";
    const handle=await rect(`${menu}.querySelector('.o-drag-btn')`);
    check(handle.top>=target.top-30&&handle.top<=target.bottom+10,'拖拽控件未定位到悬停行');
    const add=await rect(`${menu}.querySelector('.o-add-btn')`);
    await click(add);await wait(200);
    check(await evaluate("!!document.querySelector('.native-slash-menu')"),'加号未打开菜单');
    const menuRect=await rect("document.querySelector('.native-slash-menu')");
    check(menuRect.bottom>0&&menuRect.top<1200,'插入菜单没有出现在可见区域');
    const after=await evaluate("(()=>{const e=document.querySelector('.body-editor .tiptap');return {text:e.textContent,count:e.childElementCount}})()");
    check(after.text===before.text&&after.count===before.count,'点击加号插入了斜杠或新行');
    check(await evaluate(`(()=>{const e=${line};return getComputedStyle(e).backgroundColor!=='rgba(0, 0, 0, 0)'})()`),'当前行没有底色');
    check(await evaluate(`(()=>{const s=window.getSelection();return ${line}.contains(s.anchorNode)})()`),'点击加号后光标不在当前行');
    await click(add);await wait(150);
    const again=await evaluate("(()=>{const e=document.querySelector('.body-editor .tiptap');return {text:e.textContent,count:e.childElementCount}})()");
    check(again.text===before.text&&again.count===before.count,'连续点击加号创建了内容或新行');
    await key('Escape','Escape',27);await wait(100);
    await key('End','End',35);await key('Enter','Enter',13);await wait(150);
    const entered=await evaluate("(()=>{const e=document.querySelector('.body-editor .tiptap');return {text:e.textContent,count:e.childElementCount}})()");
    check(entered.text===before.text&&entered.count===before.count+1,'按回车没有正常创建新行');
    const second=await rect("document.querySelector('.body-editor .tiptap > p:nth-child(2)')");
    await mouse('mouseMoved',second.x,second.y);await wait(350);
    const secondHandle=await rect(`${menu}.querySelector('.o-drag-btn')`);
    check(secondHandle.top>=second.top-30&&secondHandle.top<=second.bottom+10,'拖拽控件没有跟随悬停切换到新行');
    const first=await rect(line);await mouse('mouseMoved',first.x,first.y);await wait(300);
    await click(await rect(`${menu}.querySelector('.o-add-btn')`));await wait(100);
    await click(await rect("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='一级标题')"));await wait(150);
    check(await evaluate("document.querySelector('.body-editor .tiptap').textContent")===before.text,'通过加号选择标题时丢失了原文');
    check(await evaluate("!!document.querySelector('.body-editor .tiptap > h1')"),'加号菜单没有在当前行应用标题');
    await call('Input.insertText',{text:'/'});await wait(150);
    check(await evaluate("!!document.querySelector('.native-slash-menu')"),'手动输入斜杠没有打开菜单');
    await key('Escape','Escape',27);await key('Backspace','Backspace',8);
    await call('Input.insertText',{text:'/'});await wait(150);
    await click(await rect("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='分栏')"));await wait(100);
    await click(await rect("document.querySelector('[aria-label=\"插入2栏\"]')"));await wait(150);
    const column="document.querySelector('.body-editor .tiptap [data-type=column] p')";
    await evaluate(`${column}.scrollIntoView({block:'center'})`);
    const columnLine=await rect(column);await mouse('mouseMoved',columnLine.x,columnLine.y);await wait(200);
    const columnBefore=await evaluate("document.querySelector('.body-editor .tiptap').textContent");
    const columnCount=await evaluate("document.querySelector('.body-editor .tiptap [data-type=column]').childElementCount");
    await click(await rect("document.querySelector('.column-insert-control')"));await wait(150);
    check(await evaluate("!!document.querySelector('.native-slash-menu')"),'栏内加号没有打开菜单');
    check(await evaluate("document.querySelector('.body-editor .tiptap').textContent")===columnBefore,'栏内加号插入了斜杠');
    check(await evaluate("document.querySelector('.body-editor .tiptap [data-type=column]').childElementCount")===columnCount,'栏内加号创建了新行');
    check(await evaluate(`getComputedStyle(${column}).backgroundColor!=='rgba(0, 0, 0, 0)'`),'栏内当前行没有底色');
    await key('Escape','Escape',27);
    await evaluate("document.querySelector('.body-editor .tiptap > p:last-child').scrollIntoView({block:'center'})");
    await click(await rect("document.querySelector('.body-editor .tiptap > p:last-child')"));
    await call('Input.insertText',{text:'/'});await wait(150);
    await evaluate("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='二张图片').scrollIntoView({block:'nearest'})");
    await click(await rect("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='二张图片')"));await wait(150);
    const slot="document.querySelector('.body-editor .tiptap [data-type=column] [data-report-image]')";
    await evaluate(`${slot}.scrollIntoView({block:'center'})`);
    const slotRect=await rect(slot);await mouse('mouseMoved',slotRect.x,slotRect.y);await wait(200);
    const slotBefore=await evaluate("document.querySelector('.body-editor .tiptap').textContent");
    const slotHtml=await evaluate(`${slot}.closest('[data-type=column]').innerHTML`);
    await click(await rect("document.querySelector('.column-insert-control')"));await wait(150);
    check(await evaluate("document.querySelector('.body-editor .tiptap').textContent")===slotBefore,'图片空槽加号创建了内容');
    await evaluate("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='自定义图片栏').scrollIntoView({block:'nearest'})");
    await click(await rect("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='自定义图片栏')"));await wait(150);
    await click(await rect("document.querySelector('dialog[open] .secondary-button')"));await wait(100);
    check(await evaluate(`${slot}.closest('[data-type=column]').innerHTML`)===slotHtml,'取消自定义布局时创建了新行');
    const slotAgain=await rect(slot);await mouse('mouseMoved',slotAgain.x,slotAgain.y);await wait(150);
    await click(await rect("document.querySelector('.column-insert-control')"));await wait(150);
    await click(await rect("[...document.querySelectorAll('.native-slash-menu [role=option]')].find(e=>e.textContent.trim()==='关键影像')"));await wait(150);
    await click(await rect("document.querySelector('.key-image-picker [role=checkbox]')"));
    check(await evaluate("document.querySelector('.key-image-picker')?.textContent.includes('插入当前栏')"),'图片空槽的菜单没有定位在当前栏');
    await click(await rect("document.querySelector('.key-image-insert')"));await wait(150);
    check(await evaluate(`${slot}.closest('[data-type=column]').querySelectorAll('[data-report-image]').length`)===2,'影像没有插入原图片槽所在栏');
    await call('Input.dispatchKeyEvent',{type:'keyDown',key:'z',code:'KeyZ',windowsVirtualKeyCode:90,modifiers:2});
    await call('Input.dispatchKeyEvent',{type:'keyUp',key:'z',code:'KeyZ',windowsVirtualKeyCode:90,modifiers:2});await wait(150);
    check(await evaluate(`${slot}.closest('[data-type=column]').innerHTML`)===slotHtml,'空槽内影像插入无法一步撤销');
    console.log('报告分栏内加号定位、不创建内容通过');
    console.log('报告正文菜单插入保留原文、手动斜杠通过');
    console.log('报告正文加号、行底色、拖拽定位及回车换行通过');
  }finally{ws.close();await fetch(`http://127.0.0.1:${port}/json/close/${tab.id}`)}
})().catch(error=>{console.error(error);process.exitCode=1});
